<div class="wrap article">
	<h1>Fianza and Deposits in Spain: What a Landlord Can Actually Ask For</h1>
	<p class="lead">
		The deposit question comes up in almost every viewing. How many months? Can they ask for
		more? Will you see it again? The rules in Spain are clearer than most people expect, and
		knowing them before you sign saves you a lot of money and argument.
	</p>

	<h2>The fianza, the legal minimum</h2>
	<p>
		Spanish law sets a legal minimum deposit called the <em>fianza</em>. For a residential lease
		(<em>arrendamiento de vivienda</em>), the landlord can ask for <strong>one month's rent</strong>.
		For any other use, like a shop or an office, it's two months. That part is not negotiable and
		it doesn't depend on how fancy the villa is.
	</p>
	<p>
		The law behind this is the Ley de Arrendamientos Urbanos, article 36. It has stayed the same
		for decades. One month for a home, two for everything else.
	</p>

	<h2>Why landlords often ask for more</h2>
	<p>
		Here's where it gets less simple. On top of the fianza, a landlord can add what's called a
		<em>garantía adicional</em>, an extra guarantee. The limit on that is tied to the length of
		the contract. For a lease of up to five years, they can ask for up to two extra months. For a
		longer contract, the cap goes up.
	</p>
	<p>So on paper the most common setup for a villa looks like this:</p>
	<ul>
		<li>One month fianza (the legal minimum)</li>
		<li>Up to two months additional guarantee</li>
		<li>Plus the first month's rent in advance</li>
	</ul>
	<p>
		That lands you at around three to four months of rent due before you get the keys. It's the
		number that surprises most expats, and it's worth budgeting for before you fall in love with
		a property.
	</p>

	<h2>What's normal in the Maresme luxury market</h2>
	<p>
		For high-end villas in Alella, Sant Andreu de Llavaneres or Sant Vicenç de Montalt, a
		three-month ask (one fianza plus two guarantee) is common. Some owners push for more if
		you're renting with no Spanish income history or if you're new to the country. Others ask
		for an <em>aval bancario</em>, a bank guarantee, instead of cash sitting in their account.
		That's rarer for homes than for offices, but it happens.
	</p>
	<p>
		If a landlord asks for six months up front, that's outside the normal range. You can push
		back. The law gives them the two extra months and that's usually the ceiling people agree on.
	</p>

	<h2>Catalonia's twist: INCASÒL</h2>
	<p>
		In Catalonia, the fianza doesn't just sit with the landlord. It has to be deposited with
		<strong>INCASÒL</strong>, the Catalan land institute. The landlord pays it in and gets a
		receipt. This matters for you in two ways. First, it's proof the deposit exists and is
		tracked. Second, if the landlord hasn't deposited it, that can become a problem at the end
		when it's time to return your money.
	</p>

	<h2>Getting the deposit back</h2>
	<p>
		When the lease ends, the landlord has to return the deposit within one month. If they want to
		deduct for damage, they need to show you receipts or justify the cost. Normal wear and tear
		doesn't count. A scuff on the wall from furniture is wear. A hole in the wall is damage. The
		difference matters when you're arguing over several thousand euros.
	</p>
	<p>
		Do a walkthrough when you move in and when you move out. Photos, dates, both of you present.
		It's the single thing that settles disputes before they start.
	</p>

	<h2>Questions to ask before you sign</h2>
	<ul>
		<li>Is the fianza deposited with INCASÒL? Can I see the receipt?</li>
		<li>How many months total do I pay up front, and which parts are returnable?</li>
		<li>What counts as damage in your eyes? Where's the line with wear and tear?</li>
		<li>Who holds the money, and who returns it at the end?</li>
	</ul>

