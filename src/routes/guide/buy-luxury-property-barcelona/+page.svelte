	<h1>Buying Luxury Property in Barcelona: The Parts People Get Wrong</h1>
	<p class="lead">
		Luxury property in Barcelona isn't a single market. It's a handful of micro-markets, each
		with its own rhythm, and the difference between them matters more than the headline price.
		Here's what to understand before you put money down.
	</p>

	<h2>Where the money actually goes</h2>
	<p>
		If you ask ten people where to buy "luxury" in Barcelona, most will say Passeig de Gràcia.
		Fair enough — the modernist apartment buildings there are some of the most beautiful in the
		world, and you pay for it. A prime apartment in the Quadrat d'Or or the upper reaches of
		Eixample can run well into the millions, and renovated ones with original ceilings and
		galleries go fast when they come up.
	</p>
	<p>
		But there's a quieter tier above that. <strong>Sarrià-Sant Gervasi</strong>, and especially
		the hills around <strong>Pedralbes</strong> and <strong>Tres Torres</strong>, is where serious
		buyers look for space — gardens, security, discretion, and houses rather than apartments.
		Pedralbes in particular has long been the address that signals old money. Prices there start
		high and don't really have an obvious ceiling.
	</p>
	<p>
		Then there's the coast. The Maresme towns of Alella, Teià, Cabrils and Sant Andreu de
		Llavaneres have quietly become the answer for buyers who want a villa with sea views and a
		pool, within 30 minutes of the city. You get far more house for the money than you do on
		Pedralbes' hill, and for a lot of people that's the point.
	</p>

	<h2>Prices, roughly</h2>
	<p>
		Numbers here move, and a "luxury" price tag depends enormously on street, floor, and state of
		repair. As a rule of thumb: a genuinely high-end apartment in prime Eixample starts around
		€1 million, and the better ones sail past that. A detached house with a garden in Sarrià or
		Pedralbes runs several million, with the hillside addresses at the top of that band. On the
		Maresme coast a solid villa starts lower than its Pedralbes equivalent, and the real premium
		is for sea views and proximity to the water.
	</p>
	<p>
		What most buyers miss is that the listed price is only part of the story. The taxes and
		fees you add on top in Catalonia can be substantial, and they're easy to underestimate if
		you're used to lower-cost markets.
	</p>

	<h2>The taxes and fees you'll actually pay</h2>
	<p>
		On a resale property, the main cost is the transfer tax (<em>ITP</em>), which in Catalonia
		is typically around 10% of the purchase price. New builds are different: you pay VAT
		(<em>IVA</em>) plus a smaller stamp duty (<em>AJD</em>). On top of either, budget for notary,
		land registry and legal fees — together usually a couple of percent. So if you're comparing a
		€2 million home, assume you'll need €200,000-plus above the asking price. It's the figure
		that reshapes budgets.
	</p>
	<p>
		A good lawyer is not optional here. They'll check the title, outstanding debts on the
		property, and make sure everything is clean before you commit. Skipping this step to save a
		few thousand euros is how expensive mistakes happen.
	</p>

	<h2>What to check before you commit</h2>
	<ul>
		<li>Is it resale or new build? The tax treatment differs, and so does the paperwork.</li>
		<li>Is there a community of owners, and what are the monthly fees?</li>
		<li>For a villa: pool, garden and irrigation costs add up, so ask about running costs.</li>
		<li>If it's a listed or period building, factor in renovation restrictions.</li>
		<li>Does the price reflect a real valuation, or optimism? Get an independent view.</li>
	</ul>

	<h2>The honest take</h2>
	<p>
		Buying luxury property in Barcelona rewards patience and local knowledge. The best properties
		here don't always hit the public portals — a meaningful share change hands quietly, through
		agencies, before they're ever listed. If you're serious, work with someone who sees that
		off-market flow. The difference between what's advertised and what's actually available is
		bigger in luxury than in almost any other segment.
	</p>

