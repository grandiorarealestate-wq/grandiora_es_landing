		Here's the thing about pool houses in Maresme: the good ones barely touch the portals. A lot
		of this stock moves <strong>off-market</strong>, through agencies that know the owners and
		match tenants directly. The listings you see on Idealista are often the leftovers that have
		been sitting there for a reason.
	</p>
