	<h2>Why Maresme, and not somewhere else on the coast</h2>
	<p>
		Maresme is the coastal strip running north-east from Barcelona, and it has one thing the
		south coast (Garraf, Sitges direction) doesn't: you're on the right side of the city for
		most international schools, and the train line hugs the coast the whole way. The R1 rodalies
		line stops in almost every town, which means you can genuinely live in a house with a pool
		and still get to Plaça de Catalunya in 35–45 minutes.
	</p>
	<p>
		The towns people actually end up in are, roughly in order of how far you are from the city:
		<strong>Alella, Teià, El Masnou, Cabrils, Vilassar de Mar, Sant Andreu de Llavaneres, Sant
		Vicenç de Montalt and Arenys de Mar</strong>. Each has a slightly different character. Alella
		is close and wine-country-ish. Sant Andreu de Llavaneres is where the big golf-and-marina
		money goes. Arenys is further out but noticeably cheaper.
	</p>

	<h2>What it costs, honestly</h2>
	<p>
		Rent for a house with a pool in Maresme is all over the place because the stock is so varied.
		A small four-bed with a modest pool in Teià or Cabrils can start around €3,000–€4,000 a
		month. A proper villa with a garden, sea views and a decent pool in Sant Andreu de Llavaneres
		or Sant Vicenç de Montalt is more like €5,000–€8,000, and the top end goes well beyond that.
		As a rule, every extra kilometre you go up the coast from Barcelona shaves something off the
		price — but also adds to your commute.
	</p>
	<p>
		By the way, the pool itself rarely drives the price up as much as people assume. What you're
		really paying for is the land, the sea view and the condition of the house. A tired house
		with a great pool will rent for less than a renovated one with a tired pool.
	</p>

	<h2>The fine print on pools</h2>
	<p>Before you fall in love with a listing, check three things:</p>
	<ul>
		<li><strong>Who maintains it?</strong> Pool and garden upkeep is usually the landlord's
		obligation for long-term residential leases, but it's worth getting it in writing. A weekly
		gardener and pool service runs a few hundred euros a month if you're left holding it.</li>
		<li><strong>Heating or not.</strong> Most Maresme pools are unheated. The season is roughly
		May to September; outside that, you're looking at a very cold dip. A heated pool is a real
		premium.</li>
		<li><strong>Water and rules.</strong> Some towns have watering restrictions in summer. Ask
		how the garden is irrigated — a house with a well costs far less to run than one on mains
		water for a big lawn.</li>
	</ul>

	<h2>How to actually find one</h2>
